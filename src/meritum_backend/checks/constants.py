"""Constants of the checks slice.

Features:
    US-SPR-01, US-SPR-07, US-SPR-11, US-BEZ-04, US-BEZ-07, F-01, F-08, F-20, F-21
"""

import re
from datetime import timedelta
from typing import Final, LiteralString

from meritum_core.checks import AnalysisStep
from meritum_core.checks.transcription import (
    MAX_AUDIO_BYTES,
    MAX_AUDIO_SECONDS,
    AudioFormat,
)

SESSION_HEADER: Final = "X-Meritum-Session"
"""Header with the random browser session id; frontend and extension send it too."""

EMPTY_KEY: Final = "errors.empty"
"""copy/pl.json key: no text of MIN_TEXT_CHARS+ characters, no link, no audio."""

TOO_LONG_KEY: Final = "errors.too_long"
"""copy/pl.json key: the text is longer than 4000 characters."""

INVALID_URL_KEY: Final = "errors.invalid_url"
"""copy/pl.json key: the link is not a full http:// or https:// address."""

TEXT_MAX_CHARS: Final = 4000
"""Longest text, as CheckRequest.text in meritum-core; masking never goes past it."""

MARKER_OPEN: Final = "["
"""First character of every personal-data marker of meritum-core ("[telefon]")."""

TEXT_FIELDS: Final = frozenset({"text", "justification"})
"""Free-text fields whose too-long error maps to TOO_LONG_KEY (check text, dispute)."""

TOO_LONG_ERROR: Final = "string_too_long"
"""pydantic error type of a string over its max_length."""

RECEIVED: Final = AnalysisStep(code="receive", status="done")
"""The only step of a check the worker has not reported on yet."""

URL_FIELDS: Final = frozenset({"url", "page_url"})
"""CheckRequest fields holding a link; their errors map to INVALID_URL_KEY."""

FOREIGN_LINK: Final = re.compile(r"(?!https?://)[a-z][a-z0-9+.-]*://\S+", re.IGNORECASE)
"""A text that is only a link with another scheme (ftp://, file://...)."""

PROGRESS_WAIT_SECONDS: Final = 0.5
"""How long a poll reads the progress stream of a running check before answering."""

AI_DISCLOSURE_HEADER: Final = "AI-Disclosure"
"""Machine-readable AI marker on a result (AI Act art. 50(2); draft-abaris-aicdh)."""

AI_DISCLOSURE_VALUE: Final = "mode=ai-originated"
"""Value of AI_DISCLOSURE_HEADER: the answer was generated by an AI system."""

AI_DISCLOSURE_EXAMPLE: Final = (
    f'{AI_DISCLOSURE_VALUE}; model="anthropic/claude-haiku-5-5";'
    ' provider="openrouter"; date=@1795262400'
)
"""OpenAPI example of AI_DISCLOSURE_HEADER for a result with an AI marker."""

NO_SESSION_DETAIL: Final = f"send the {SESSION_HEADER} header"
"""400 detail: a check without a browser session (a client bug, not user copy)."""

BAD_SESSION_DETAIL: Final = (
    f"send a valid {SESSION_HEADER} header (8 to 64 characters);"
    " a session_id in the body must equal it"
)
"""400 detail: the session id has the wrong length or differs from the body's."""

NO_CHANNEL_USER_DETAIL: Final = "Discord, SMS and MCP checks send channel_user_id"
"""400 detail: a sessionless channel sent no user id to hash (a client bug)."""

NO_SALT_DETAIL: Final = "channel user hashing is not configured"
"""503 detail: MERITUM_CHANNEL_HASH_SALT is unset, so no sessionless check starts."""

NOT_FOUND_DETAIL: Final = "check not found"
"""404 detail: no check workflow has this id."""

VERIFY_STEP: Final = "verify_citations"
"""Step after which a result may carry verdicts; before it the result is withheld."""

FINISHED_STEP_STATES: Final = frozenset({"done", "skipped"})
"""States of a step that will not change any more (a failed one may be retried)."""

AUDIO_RETENTION: Final = timedelta(days=30)
"""How long an uploaded recording is kept at most: the check record's retention."""

AUDIO_CONTENT_TYPES: Final = {
    AudioFormat.OGG_OPUS: "audio/ogg",
    AudioFormat.MP3: "audio/mpeg",
    AudioFormat.M4A: "audio/mp4",
    AudioFormat.WAV: "audio/wav",
}
"""MIME type stored with a recording, by the format read from its bytes."""

AUDIO_TOO_LARGE_KEY: Final = "errors.audio_too_large"
"""copy/pl.json key: the recording is over MAX_AUDIO_BYTES."""

AUDIO_TOO_LONG_KEY: Final = "errors.audio_too_long"
"""copy/pl.json key: the recording is over MAX_AUDIO_SECONDS."""

AUDIO_FORMAT_KEY: Final = "out_of_scope_code.audio"
"""copy/pl.json key: this recording cannot be checked (design-system#90)."""

AUDIO_UPLOAD_LIMIT: Final = "10/minute;30/day"
"""Uploads per client address; each can keep MAX_AUDIO_BYTES for 30 days."""

STORAGE_DETAIL: Final = "file storage unavailable"
"""503 detail: the BlobStore failed (a server fault, not user copy)."""

AUDIO_FORMATS: Final = ("OGG", "MP3", "M4A", "WAV")
"""Formats named to the person ({formats} in form.audio_limits)."""

AUDIO_MAX_MB: Final = MAX_AUDIO_BYTES // (1024 * 1024)
"""{max_mb} of the copy: MAX_AUDIO_BYTES in MiB."""

AUDIO_MAX_MINUTES: Final = MAX_AUDIO_SECONDS // 60
"""{max_minutes} of the copy: MAX_AUDIO_SECONDS in minutes."""

RESULT_CACHE_TTL: Final = timedelta(hours=2)
"""How long a cached result is served; new corpus snapshots do not cut it (ADR-22)."""

CACHE_HIT_RETENTION: Final = timedelta(days=30)
"""How long the CheckRecord of a check served from the cache is kept (ADR-13)."""

UNANSWERED_VERDICT: Final = "insufficient_evidence"
"""Verdict of a claim with no answer; every cache hit escalates it (US-MOD-03)."""

CACHE_HIT_REASON: Final = "cache_hit"
"""EscalateClaimInput.reason of the escalation a cache hit starts (core/019)."""

SUBSTANTIVE_FIELDS: Final = (
    "status",
    "claims",
    "message",
    "out_of_scope_code",
    "limitations",
    "limitation_codes",
    "transcript",
    "source_warning",
    "ai_marker",
    "corpus_version",
)
"""The fields a CheckResult and a CachedResult share: the substantive part (ADR-19)."""

CACHE_CONNECT_TIMEOUT_SECONDS: Final = 3
"""How long the result cache waits for a database connection before it misses."""

LOOKUP_CACHE: Final[LiteralString] = (
    "SELECT entry FROM result_cache WHERE key = %(key)s AND expires_at > %(now)s"
)
"""The live entry of one input key."""

LINK_CHECK: Final[LiteralString] = (
    "INSERT INTO result_cache_checks (check_id, key, served)"
    " VALUES (%(check_id)s, %(key)s, %(served)s::jsonb)"
    " ON CONFLICT (check_id) DO NOTHING"
)
"""Remember the input key of one check and, for a hit, the entry it got."""

PRUNE_LINKS: Final[LiteralString] = (
    "DELETE FROM result_cache_checks WHERE linked_at < now() - interval '1 day'"
)
"""Forget check keys older than any check still being polled."""

PRUNE_ENTRIES: Final[LiteralString] = (
    "DELETE FROM result_cache WHERE expires_at < now() - interval '1 day'"
)
"""Drop entries a day past expiry; a fill would replace them anyway."""

FILL_CACHE: Final[LiteralString] = """
    INSERT INTO result_cache (key, entry, expires_at)
    SELECT key, %(entry)s::jsonb, %(expires_at)s
    FROM result_cache_checks WHERE check_id = %(check_id)s
    ON CONFLICT (key) DO UPDATE
    SET entry = EXCLUDED.entry, expires_at = EXCLUDED.expires_at
    WHERE result_cache.expires_at <= %(now)s
"""
"""Store a check's result under its key, unless a live entry is already there."""

ENTRY_OF_CHECK: Final[LiteralString] = (
    "SELECT served FROM result_cache_checks"
    " WHERE check_id = %(check_id)s AND served IS NOT NULL"
)
"""The entry a cache hit got; kept with the hit, so a later refill never changes it."""
