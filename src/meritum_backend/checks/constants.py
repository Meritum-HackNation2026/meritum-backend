"""Constants of the checks slice.

Features:
    US-SPR-01, US-SPR-07, US-BEZ-04, US-BEZ-07, F-01, F-20, F-21
"""

import re
from typing import Final

from meritum_core.checks import AnalysisStep
from meritum_core.security.constants import EMAIL_MARKER, PESEL_MARKER, PHONE_MARKER

SESSION_HEADER: Final = "X-Meritum-Session"
"""Header with the random browser session id; frontend and extension send it too."""

EMPTY_KEY: Final = "errors.empty"
"""copy/pl.json key: no text of MIN_TEXT_CHARS+ characters, no link, no audio."""

TOO_LONG_KEY: Final = "errors.too_long"
"""copy/pl.json key: the text is longer than 4000 characters."""

INVALID_URL_KEY: Final = "errors.invalid_url"
"""copy/pl.json key: the link is not a full http:// or https:// address."""

TEXT_MAX_CHARS: Final = 4000
"""Longest text, as CheckRequest.text in meritum-core; masking never goes past it."""

MARKERS: Final = (PHONE_MARKER, EMAIL_MARKER, PESEL_MARKER)
"""Every personal-data marker mask_personal_data writes."""

MARKER_OPEN: Final = "["
"""First character of every personal-data marker of meritum-core ("[telefon]")."""

TEXT_FIELD: Final = "text"
"""CheckRequest field with the free text."""

TOO_LONG_ERROR: Final = "string_too_long"
"""pydantic error type of a string over its max_length."""

RECEIVED: Final = AnalysisStep(code="receive", status="done")
"""The only step of a check the worker has not reported on yet."""

URL_FIELDS: Final = frozenset({"url", "page_url"})
"""CheckRequest fields holding a link; their errors map to INVALID_URL_KEY."""

FOREIGN_LINK: Final = re.compile(r"(?!https?://)[a-z][a-z0-9+.-]*://\S+", re.IGNORECASE)
"""A text that is only a link with another scheme (ftp://, file://...)."""

PROGRESS_WAIT_SECONDS: Final = 0.5
"""How long a poll reads the progress stream of a running check before answering."""

AI_DISCLOSURE_HEADER: Final = "AI-Disclosure"
"""Machine-readable AI marker on a result (AI Act art. 50(2); draft-abaris-aicdh)."""

AI_DISCLOSURE_VALUE: Final = "mode=ai-originated"
"""Value of AI_DISCLOSURE_HEADER: the answer was generated by an AI system."""

NO_SESSION_DETAIL: Final = f"send the {SESSION_HEADER} header"
"""400 detail: a check without a browser session (a client bug, not user copy)."""

BAD_SESSION_DETAIL: Final = f"send a valid {SESSION_HEADER} header (8 to 64 characters)"
"""400 detail: the session id has the wrong length."""

SESSIONLESS_DETAIL: Final = (
    "Discord, SMS and MCP checks come through their channel adapter"
)
"""400 detail: these channels need a hashed channel user id (backend#27)."""

NOT_FOUND_DETAIL: Final = "check not found"
"""404 detail: no check workflow has this id."""
